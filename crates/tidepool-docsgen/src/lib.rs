//! The doc site's reference, rendered from the sources the server itself
//! serves.
//!
//! `website/` is a `VitePress` site whose prose is written by hand and whose
//! reference tables are not written at all. Everything under
//! `website/reference/generated/` comes from here: the config file reference
//! from the JSON Schemas of `tidepool-config` (so the doc comments on the
//! config types are the docs), the HTTP reference from the endpoint table
//! (the one `api_router` is folded over), the MCP tools from the list
//! `tools/list` answers with, and `openapi.json` from
//! `tidepool_server::openapi::document` over the retail example. Nothing here
//! names a config key, an endpoint or a tool. This is kayak's docsgen, for
//! tidepool's sources.
//!
//! The generated files are **markdown partials**, not pages: no title, no
//! front matter. A prose page pulls one in with `VitePress`'
//! `<!--@include: -->`. The site owns the narrative and the order, this owns
//! every table, and neither restates the other.
//!
//! [`files`] returns what should be on disk, `main.rs` writes it, and
//! `tests/site.rs` compares it with what is committed, so a stale site is a
//! failing test.

// Every string here is assembled by appending, once per file. `format!` into
// `push_str` is the readable spelling of that.
#![allow(clippy::format_push_string)]

pub mod schema;

use std::path::{Path, PathBuf};

use serde_json::{Value, json};
use tidepool_config::ConfigSet;
use tidepool_model::{Catalog, Model, compile};
use tidepool_protocol::api_docs::{ApiDoc, Body, TAGS, Tag, endpoints, schemas};

use crate::schema::{Renderer, anchor, cell, paragraphs};

/// Where generated partials live, relative to the site root.
pub const GENERATED: &str = "reference/generated";

/// The line every generated file opens with. An HTML comment: it renders as
/// nothing and reads as a warning in an editor.
const BANNER: &str = "<!-- generated by `just docs` from tidepool's schemas, endpoint table and MCP tools. do not edit. -->";

/// One file the site expects to find, and what should be in it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Path relative to the site root (`website/`), with `/` separators.
    pub path: String,
    pub contents: String,
}

/// The repository root.
#[must_use]
pub fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The retail example's model: what the OpenAPI document's per-table paths
/// are written for.
///
/// # Errors
/// The example can't be read or doesn't compile.
pub fn retail() -> Result<Model, String> {
    let dir = repository().join("examples/retail");
    let (set, mut diagnostics) =
        ConfigSet::load_dir(&dir).map_err(|e| format!("reading {}: {e}", dir.display()))?;
    let (compiled, more) = compile(&set, &Catalog::default());
    diagnostics.extend(more);
    compiled.map(|c| c.model).ok_or_else(|| {
        format!(
            "the retail example doesn't compile:\n{}",
            tidepool_config::diag::render_all(&diagnostics, &set.files)
        )
    })
}

/// Everything the generator produces, in a stable order.
///
/// # Errors
/// The retail example can't be read or doesn't compile.
pub fn files() -> Result<Vec<GeneratedFile>, String> {
    let mut out = Vec::new();

    for kind in tidepool_config::schema::KINDS {
        let Some(schema) = tidepool_config::schema::schema(kind) else {
            continue;
        };
        out.push(GeneratedFile {
            path: format!("{GENERATED}/config/{kind}.md"),
            contents: partial(&config_reference(kind, &schema)),
        });
    }

    let api = endpoints();
    out.push(GeneratedFile {
        path: format!("{GENERATED}/api/endpoints.md"),
        contents: partial(&api_reference(&api)),
    });
    out.push(GeneratedFile {
        path: format!("{GENERATED}/api/schemas.md"),
        contents: partial(&schema_reference()),
    });

    let tools = tidepool_server::mcp_tools();
    out.push(GeneratedFile {
        path: format!("{GENERATED}/mcp/tools.md"),
        contents: partial(&tool_reference(&tools)),
    });

    out.push(GeneratedFile {
        path: ".vitepress/generated/sidebar.json".to_string(),
        contents: pretty_json(&sidebar(&tools)),
    });
    out.push(GeneratedFile {
        path: "public/openapi.json".to_string(),
        contents: pretty_json(&tidepool_server::openapi::document(&retail()?)),
    });

    Ok(out)
}

/// A generated partial: the banner, then the body, then exactly one newline.
fn partial(body: &str) -> String {
    format!("{BANNER}\n\n{}\n", body.trim_end())
}

fn pretty_json(value: &Value) -> String {
    let rendered = serde_json::to_string_pretty(value).unwrap_or_else(|_| "{}".to_string());
    format!("{rendered}\n")
}

// --------------------------------------------------------------------- config

/// One kind of config file: its keys, then each type they use.
fn config_reference(kind: &str, schema: &Value) -> String {
    let mut renderer = Renderer::new(kind);
    let mut out = renderer.body(schema);
    out.push_str("\n\n");
    out.push_str(&renderer.sections());
    out
}

// ------------------------------------------------------------------------ api

/// Every endpoint, grouped by tag in the order of [`TAGS`].
fn api_reference(api: &[ApiDoc]) -> String {
    let mut out = String::new();
    for tag in TAGS {
        let of_tag: Vec<&ApiDoc> = api.iter().filter(|e| e.tag == tag).collect();
        if of_tag.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "## {} {{#{}}}\n\n{}\n\n",
            tag.label(),
            tag_anchor(tag),
            paragraphs(tag.description())
        ));
        for endpoint in of_tag {
            out.push_str(&endpoint_section(endpoint));
        }
    }
    out
}

fn tag_anchor(tag: Tag) -> String {
    format!("api-{}", tag.label())
}

/// The anchor of one endpoint: its operation id, which is unique and stable.
#[must_use]
pub fn endpoint_anchor(endpoint: &ApiDoc) -> String {
    format!("op-{}", endpoint.operation_id().to_lowercase())
}

fn endpoint_section(endpoint: &ApiDoc) -> String {
    let mut out = format!(
        "### `{} {}` {{#{}}}\n\n**{}** · access: `{}`\n\n{}\n\n",
        endpoint.method.label(),
        endpoint.path,
        endpoint_anchor(endpoint),
        schema::escape(endpoint.summary),
        endpoint.access.label(),
        paragraphs(endpoint.description),
    );
    for (title, params) in [
        ("path parameter", &endpoint.params),
        ("query parameter", &endpoint.query),
    ] {
        if params.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "| {title} | description | example |\n| --- | --- | --- |\n"
        ));
        for param in params {
            out.push_str(&format!(
                "| `{}` | {} | `{}` |\n",
                param.name,
                cell(param.description),
                param.example
            ));
        }
        out.push('\n');
    }
    if let Some(request) = &endpoint.request {
        out.push_str(&format!(
            "Request: {}. {}\n\n",
            body(request.body),
            schema::escape(request.description)
        ));
    }
    out.push_str("| status | body | description |\n| --- | --- | --- |\n");
    for response in &endpoint.responses {
        out.push_str(&format!(
            "| `{}` | {} | {} |\n",
            response.status,
            body(response.body),
            cell(response.description)
        ));
    }
    out.push('\n');
    out
}

/// A body, in a few words, with a link to its schema.
fn body(body: Body) -> String {
    let link = |name: &str| format!("[`{name}`](/reference/schemas#{})", anchor("schema", name));
    match body {
        Body::None => "none".to_string(),
        Body::Json(name) => link(name),
        Body::JsonArray(name) => format!("list of {}", link(name)),
        Body::AnyJson => "JSON".to_string(),
        Body::Rows => "rows: JSON, NDJSON or Arrow IPC".to_string(),
        Body::JsonOrCsv(name) => format!("{} or CSV", link(name)),
        Body::Text => "text".to_string(),
    }
}

/// Every body schema the endpoints name, then the types they share.
fn schema_reference() -> String {
    let all = schemas();
    let mut renderer = Renderer::new("schema");
    renderer.external(all.keys().map(|k| (*k).to_string()));
    let mut out = String::new();
    for (name, schema) in &all {
        out.push_str(&format!("## `{name}` {{#{}}}\n\n", renderer.anchor(name)));
        out.push_str(&renderer.body(schema));
        out.push_str("\n\n");
    }
    out.push_str(&renderer.sections());
    out
}

// ------------------------------------------------------------------------ mcp

fn tool_anchor(name: &str) -> String {
    format!("tool-{}", name.replace('_', "-"))
}

/// Every tool `tools/list` answers with: its description and its arguments.
fn tool_reference(tools: &Value) -> String {
    let mut out = String::new();
    for tool in tools.as_array().into_iter().flatten() {
        let name = tool["name"].as_str().unwrap_or_default();
        let title = tool["title"].as_str().unwrap_or_default();
        let read_only = tool["annotations"]["readOnlyHint"].as_bool() == Some(true);
        out.push_str(&format!(
            "## `{name}` {{#{}}}\n\n**{}**{}\n\n{}\n\n",
            tool_anchor(name),
            schema::escape(title),
            if read_only { " · read only" } else { "" },
            paragraphs(tool["description"].as_str().unwrap_or_default()),
        ));
        let input = &tool["inputSchema"];
        let has_arguments = input["properties"]
            .as_object()
            .is_some_and(|p| !p.is_empty());
        if has_arguments {
            let prefix = tool_anchor(name);
            let mut renderer = Renderer::new(&prefix);
            out.push_str(&renderer.body(input));
            out.push_str("\n\n");
            out.push_str(&renderer.sections().replace("## ", "### "));
        } else {
            out.push_str("No arguments.\n\n");
        }
    }
    out
}

// -------------------------------------------------------------------- sidebar

/// The sidebar entries that follow the sources: one per endpoint group and
/// one per tool. The config pages are prose pages, listed by hand.
fn sidebar(tools: &Value) -> Value {
    let api: Vec<Value> = TAGS
        .iter()
        .map(|tag| json!({ "text": tag.label(), "link": format!("/reference/api#{}", tag_anchor(*tag)) }))
        .collect();
    let mcp: Vec<Value> = tools
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|t| t["name"].as_str())
        .map(
            |name| json!({ "text": name, "link": format!("/reference/mcp#{}", tool_anchor(name)) }),
        )
        .collect();
    json!({ "api": api, "mcp": mcp })
}
